// Regenerates docs/PROMPTS.md from prompts/*.md, prompts/guides/*.md and prompts/index.json:
//   node src/tools/prompts-doc.ts
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { guidesOf } from "../agents/guides.ts";

const root = fileURLToPath(new URL("../../", import.meta.url));

interface PromptMeta {
  model: string;
  step: string;
  purpose: string;
}

export function renderPromptsDoc(index: Record<string, PromptMeta>, texts: Record<string, string>, guides: Record<string, string> = {}): string {
  const missingMeta = Object.keys(texts).filter((n) => !index[n]);
  const missingFile = Object.keys(index).filter((n) => texts[n] === undefined);
  if (missingMeta.length || missingFile.length) {
    throw new Error(`prompts/index.json is out of sync: no entry for ${missingMeta.join(", ") || "-"}; no file for ${missingFile.join(", ") || "-"}`);
  }
  const guidesBy = (name: string) => [...new Set(guidesOf(name, texts[name]).values())];
  const out = [
    "# Prompts",
    "",
    "Generated by `node src/tools/prompts-doc.ts` from `prompts/*.md`, `prompts/guides/*.md` and `prompts/index.json`. Don't edit by hand.",
    "`{placeholders}` are filled in by the orchestrator. A prompt's `{guide}` is the path of its own [guide](#guides), `{<name>Guide}`",
    "that of `prompts/guides/<name>.md`: each agent gets a copy of the guides its prompt names, in its request's `data/guides/`.",
    "",
    "| Prompt | Model | Step | Purpose |",
    "|---|---|---|---|",
    ...Object.entries(index).map(([n, m]) => `| [${n}](#${n}) | ${m.model} | ${m.step} | ${m.purpose} |`),
  ];
  for (const [name, meta] of Object.entries(index)) {
    const placeholders = [...new Set([...texts[name].matchAll(/\{([A-Za-z][A-Za-z0-9_]*)\}/g)].map((m) => m[1]))];
    const used = guidesBy(name);
    const missingGuide = used.filter((g) => guides[g] === undefined);
    if (missingGuide.length) throw new Error(`${name} names guides with no file in prompts/guides/: ${missingGuide.join(", ")}`);
    out.push(
      "",
      `## ${name}`,
      "",
      `${meta.model} · ${meta.step} · inputs: ${placeholders.map((p) => `\`${p}\``).join(", ") || "none"}${used.length ? ` · guides: ${used.map((g) => `[${g}](#guide-${g})`).join(", ")}` : ""}`,
      "",
      "```",
      texts[name].trimEnd(),
      "```",
    );
  }
  if (Object.keys(guides).length) out.push("", "# Guides", "", "The long parts of the prompts, from `prompts/guides/`, given to agents as they are.");
  for (const [name, text] of Object.entries(guides)) {
    const by = Object.keys(index).filter((n) => guidesBy(n).includes(name));
    out.push("", `<a id="guide-${name}"></a>`, "", `## Guide: ${name}`, "", `Read by: ${by.map((n) => `[${n}](#${n})`).join(", ") || "no prompt"}`, "", "````markdown", text.trimEnd(), "````");
  }
  return out.join("\n") + "\n";
}

export function generate(): string {
  const index = JSON.parse(readFileSync(`${root}prompts/index.json`, "utf8")) as Record<string, PromptMeta>;
  const texts: Record<string, string> = {};
  for (const f of readdirSync(`${root}prompts`)) {
    if (f.endsWith(".md")) texts[f.slice(0, -3)] = readFileSync(`${root}prompts/${f}`, "utf8");
  }
  const guides: Record<string, string> = {};
  for (const f of readdirSync(`${root}prompts/guides`).sort()) {
    if (f.endsWith(".md")) guides[f.slice(0, -3)] = readFileSync(`${root}prompts/guides/${f}`, "utf8");
  }
  return renderPromptsDoc(index, texts, guides);
}

if (import.meta.main) {
  writeFileSync(`${root}docs/PROMPTS.md`, generate());
}
