// Regenerates docs/PROMPTS.md from prompts/*.md and prompts/index.json:
//   node src/tools/prompts-doc.ts
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("../../", import.meta.url));

interface PromptMeta {
  model: string;
  step: string;
  purpose: string;
}

export function renderPromptsDoc(index: Record<string, PromptMeta>, texts: Record<string, string>): string {
  const missingMeta = Object.keys(texts).filter((n) => !index[n]);
  const missingFile = Object.keys(index).filter((n) => texts[n] === undefined);
  if (missingMeta.length || missingFile.length) {
    throw new Error(`prompts/index.json is out of sync: no entry for ${missingMeta.join(", ") || "-"}; no file for ${missingFile.join(", ") || "-"}`);
  }
  const out = [
    "# Prompts",
    "",
    "Generated by `node src/tools/prompts-doc.ts` from `prompts/*.md` and `prompts/index.json`. Don't edit by hand.",
    "`{placeholders}` are filled in by the orchestrator.",
    "",
    "| Prompt | Model | Step | Purpose |",
    "|---|---|---|---|",
    ...Object.entries(index).map(([n, m]) => `| [${n}](#${n}) | ${m.model} | ${m.step} | ${m.purpose} |`),
  ];
  for (const [name, meta] of Object.entries(index)) {
    const placeholders = [...new Set([...texts[name].matchAll(/\{([A-Za-z][A-Za-z0-9_]*)\}/g)].map((m) => m[1]))];
    out.push(
      "",
      `## ${name}`,
      "",
      `${meta.model} · ${meta.step} · inputs: ${placeholders.map((p) => `\`${p}\``).join(", ") || "none"}`,
      "",
      "```",
      texts[name].trimEnd(),
      "```",
    );
  }
  return out.join("\n") + "\n";
}

export function generate(): string {
  const index = JSON.parse(readFileSync(`${root}prompts/index.json`, "utf8")) as Record<string, PromptMeta>;
  const texts: Record<string, string> = {};
  for (const f of readdirSync(`${root}prompts`)) {
    if (f.endsWith(".md")) texts[f.slice(0, -3)] = readFileSync(`${root}prompts/${f}`, "utf8");
  }
  return renderPromptsDoc(index, texts);
}

if (import.meta.main) {
  writeFileSync(`${root}docs/PROMPTS.md`, generate());
}
